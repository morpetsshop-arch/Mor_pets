import express from 'express';
import session from 'express-session';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { config, cop } from './config/index.js';
import { Cart } from './models/cart.model.js';
import routes from './routes/index.js';
import { Product } from './models/product.model.js';
const dir = path.dirname(fileURLToPath(import.meta.url));
const app = express();
app.set('view engine', 'ejs');
app.set('views', path.join(dir, 'views'));
app.use(express.urlencoded({ extended: false }));
app.use(express.static(path.join(dir, '../public')));
app.use(session({ secret: config.sessionSecret, resave: false, saveUninitialized: false, cookie: { httpOnly: true, maxAge: 7 * 864e5 } }));
app.use((req, res, next) => { Object.assign(res.locals, { brand: config.brand, money: cop, cartCount: Cart.count(req.session), aromas: Product.aromas() }); next(); });
app.use(routes);
app.use((req, res) => res.status(404).render('404', { title: 'No encontrada' }));
export default app;
